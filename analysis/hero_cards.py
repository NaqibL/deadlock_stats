"""Generate a card for every hero from the sheet, the formulas and the catalogues.

    python analysis/catalogue.py      # first: the cards read the catalogues
    python analysis/hero_cards.py

Writes ``analysis/heroes/<hero>.md`` (one card each), ``analysis/heroes/README.md`` (an index
comparing all heroes) and ``analysis/heroes/hero_summary.csv``. Method: ``analysis/framework.md``
section 4.1. Every number is computed from ``output/`` with the rules in ``analysis/formulas.py``;
the assumptions those rules carry are listed on each card.
"""

from __future__ import annotations

import csv
import re
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import formulas as F  # noqa: E402

OUT = HERE / "heroes"
CAT = HERE / "catalogues"

CHECKPOINTS = [  # (label, souls collected)
    ("kit complete", 3200),
    ("first ability maxed", 6000),
    ("second ability maxed", 12800),
    ("third ability maxed", 24600),
    ("last boon", 48600),
]
REFERENCE_SP = (0, 50, 150)
HARD_CC = ("stun", "sleep", "immobilize", "petrify", "freeze", "time stop", "hex", "fear", "tether", "lift",
           "displacement", "curse")
DENIAL = ("silence", "disarm", "movement silence", "curse")


def rows(name):
    with open(CAT / f"{name}.csv", newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def n(v):
    try:
        f = float(v)
        return None if f != f else f
    except (TypeError, ValueError):
        return None


def f(v, d=1):
    if v is None:
        return ""
    s = f"{v:.{d}f}"
    return s.rstrip("0").rstrip(".") if "." in s else s


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


# ---------------------------------------------------------------- kit damage


def ability_damage(dmg_rows, ability, sp, upgraded):
    """Rough damage of one cast at a spirit power: the largest flat damage property, plus what
    upgrades add to that property; per-second properties times the ability's duration when it has one.
    A comparison figure only: abilities with several damage parts or conditions are simplified."""
    base_rows = [r for r in dmg_rows if r["name"] == ability["name"] and r["tier"] in ("", "0")]
    best = 0.0
    for r in base_rows:
        if r["kind"] not in ("flat", "per second"):
            continue
        val = n(r["base"]) or 0
        coef = n(r["spirit_coef"]) or 0
        if upgraded:
            for u in dmg_rows:
                if u["name"] == ability["name"] and u["tier"] not in ("", "0") and u["property"] == r["property"]:
                    val += n(u["base"]) or 0
                    coef += n(u["spirit_coef"]) or 0
        amount = val + coef * sp
        if r["kind"] == "per second":
            dur = n(ability["duration"])
            if not dur:
                continue
            amount *= dur
        best = max(best, amount)
    return best


# ---------------------------------------------------------------- one hero


def card(h, ab, dmg, cc, dfn, ranks):
    name = h["name"]
    lines = [f"# {name}", ""]
    tags = "; ".join(x for x in (h["hero_type"], h["hero_tags"], h["gun_tag"]) if x)
    lines += [f"**{tags}.** {h['role'] or 'No role line in the game files.'}", "",
              "Generated by `python analysis/hero_cards.py` from `output/` and `analysis/catalogues/`. "
              "Labels as in `analysis/formulas.md`; the assumptions are listed at the end.", ""]

    # Body and gun at checkpoints.
    lines += ["## Growth at the checkpoints", "",
              "Boons only: no items, no investment. Souls are souls collected.", "",
              "| Checkpoint | Souls | Boons | Health | Gun DPS | Spirit power | Light melee | Heavy melee |",
              "|---|---|---|---|---|---|---|---|"]
    for label, souls in CHECKPOINTS:
        b = F.level_at(souls)["total_boons"]
        lines.append(f"| {label} | {souls:,} | {b} | {f(F.hero_stat(name, 'base_health', b), 0)} | "
                     f"{f(F.hero_stat(name, 'weapon_dps_level_1', b))} | {f(F.spirit_power_from_boons(name, b))} | "
                     f"{f(F.hero_stat(name, 'light_melee', b))} | {f(F.hero_stat(name, 'heavy_melee', b))} |")
    lines.append("")

    traits = []
    for col, label in (("base_bullet_resist", "bullet resist"), ("base_spirit_resist", "spirit resist"),
                       ("base_melee_resist", "melee resist"), ("bullet_resist_per_boon", "bullet resist per boon"),
                       ("spirit_resist_per_boon", "spirit resist per boon"), ("debuff_resist", "debuff resist"),
                       ("innate_bullet_lifesteal_pct", "bullet lifesteal"),
                       ("headshot_damage_taken_reduction_pct", "headshot damage taken reduction")):
        v = n(h[col])
        if v:
            traits.append(f"{label} {f(v, 3)}%")
    for col, label in (("bullet_lifesteal_effectiveness", "bullet lifesteal effectiveness"),
                       ("spirit_lifesteal_effectiveness", "spirit lifesteal effectiveness")):
        v = n(h[col])
        if v is not None and v != 1:
            traits.append(f"{label} ×{f(v, 2)}")
    lines += ["## Body", "",
              f"- Health {h['base_health']} + {h['health_per_boon']} per boon "
              f"(per-boon growth ranks {ranks['health_per_boon'][name]} of 44, 1 = most). "
              f"Regen {h['health_regen']}/s.",
              f"- Move speed {h['move_speed']} m/s, sprint +{h['sprint_speed']}, stamina {h['stamina']} "
              f"({h['stamina_recovery_seconds']} s each), dash {h['dash_distance']} m.",
              f"- Traits: {', '.join(traits) if traits else 'none beyond the defaults'}.", ""]

    shots = F.shots_per_second(name)
    sus = n(h["sustained_dps_level_1"]) / n(h["weapon_dps_level_1"])
    head = n(h["headshot_bonus_scale_pct"])
    growth = n(h["dps_per_boon"]) * 35 / n(h["weapon_dps_level_1"]) * 100
    lines += ["## Gun", "",
              f"- {h['damage_per_shot']} damage per shot ({h['pellets_per_shot']} pellet(s) of {h['bullet_damage']}, "
              f"+{h['bullet_damage_per_boon']} per boon), {f(shots, 2)} shots per second"
              f"{' when spun up' if n(h['fire_rate_max_spin']) else ''}, clip {h['clip_size']}, reload {h['reload_time']} s"
              f"{' (one bullet at a time)' if h['reloads_single_bullets'] == 'True' else ''}.",
              f"- DPS {f(n(h['weapon_dps_level_1']))} at 0 boons, +{f(n(h['dps_per_boon']), 2)} per boon: "
              f"+{f(growth, 0)}% over 35 boons (growth ranks {ranks['dps_growth'][name]} of 44). "
              f"Sustained, with reloads, is {f(sus * 100, 0)}% of burst.",
              f"- **Triggers:** {f(shots, 1)} shots per second ranks {ranks['shots'][name]} of 44 for on-hit items "
              f"and build-up items (formulas.md §5).",
              f"- Falloff from {h['falloff_start']} m to {h['falloff_end']} m, keeping {f(n(h['falloff_end_damage_scale']) * 100, 0)}% "
              f"at the end. Bullet speed {h['bullet_velocity']} m/s.",
              f"- Headshots: {'cannot headshot' if h['can_headshot'] == 'False' else ('normal bonus' if not head else f'bonus scale {f(head, 0)}%')}.",
              ""]

    # Abilities.
    lines += ["## Abilities", ""]
    kit_rows = [a for a in ab if a["hero"] == name and not a["form"]]
    form_rows = [a for a in ab if a["hero"] == name and a["form"]]
    for a in kit_rows + form_rows:
        owner = a["form"] or name
        drows = [r for r in dmg if r["owner"] == owner and r["name"] == a["name"]]
        crows = [r for r in cc if r["owner"] == owner and r["name"] == a["name"]]
        frows = [r for r in dfn if r["owner"] == owner and r["name"] == a["name"]]
        cdtxt = f"cooldown {a['cooldown']} s" if a["cooldown"] else "no cooldown listed"
        if n(a["charges"]) and n(a["charges"]) > 1:
            cdtxt += f", {f(n(a['charges']), 0)} charges ({a['charge_cooldown'] or '?'} s between)"
        slot = "ultimate" if a["slot"] == "4" else f"slot {a['slot']}"
        form = f" ({a['form']})" if a["form"] else ""
        lines += [f"### {a['slot']}. {a['name']}{form}: {slot}, {cdtxt}", "", a["description"], ""]
        items = []
        for r in drows:
            if r["tier"] not in ("", "0"):
                continue
            sc = []
            if n(r["spirit_coef"]):
                sc.append(f"+{f(n(r['spirit_coef']), 3)} × spirit power")
            if n(r["weapon_pct_coef"]):
                sc.append(f"+{f(n(r['weapon_pct_coef']), 3)} × weapon damage %")
            gain = f" (+{f(n(r['gain_per_100_sp']), 0)}% per 100 spirit power)" if n(r["gain_per_100_sp"]) else ""
            unit = "% of health" if r["kind"] == "target health %" else ("/s" if r["kind"] == "per second" else "")
            items.append(f"{r['property']} {f(n(r['base']), 2)}{unit} {' '.join(sc)}{gain} [{r['damage_type']}, {r['kind']}]")
        if items:
            lines.append("- **Damage:** " + "; ".join(items) + ".")
        if a["other_scaling"]:
            lines.append(f"- **Other scaling:** {a['other_scaling']}.")
        ctl = [f"{r['cc_type']} {f(n(r['value']), 2)}{r['unit']}".strip() +
               (f" (tier {r['tier']} adds)" if r["tier"] not in ("", "0") else "") +
               (" (from description)" if r.get("basis") == "description" else "") for r in crows]
        if ctl:
            lines.append("- **Control:** " + "; ".join(ctl) + ".")
        dft = [f"{r['effect']} {f(n(r['value']), 2)}{r['unit']}".strip() +
               (f" (tier {r['tier']})" if r["tier"] not in ("", "0") else "") for r in frows]
        if dft:
            lines.append("- **Defence, sustain, debuffs:** " + "; ".join(dft) + ".")
        for t in (1, 2, 3):
            lines.append(f"- Tier {t} ({(1, 2, 5)[t - 1]} AP): {a[f'upgrade_{t}'].split(' | ')[0]}")
        lines.append("")

    # Kit damage by spirit power.
    kit = [a for a in kit_rows]
    owner_dmg = [r for r in dmg if r["owner"] == name]
    lines += ["## Kit damage by spirit power", "",
              "One cast of each ability: the largest damage property, plus per-second damage times duration where the "
              "ability has one. Upgraded = all three tiers. A rough comparison figure: conditional damage, several "
              "hits and summons are simplified, per-second damage is taken at its listed maximum, and scaling from "
              "melee damage, weapon damage % and boons is left out.", "",
              "| Spirit power | " + " | ".join(a["name"] for a in kit) + " | Kit total | Kit total, upgraded |",
              "|---|" + "---|" * (len(kit) + 2)]
    totals = {}
    for sp in REFERENCE_SP:
        per = [ability_damage(owner_dmg, a, sp, False) for a in kit]
        up = sum(ability_damage(owner_dmg, a, sp, True) for a in kit)
        totals[sp] = (sum(per), up)
        lines.append(f"| {sp} | " + " | ".join(f(x, 0) for x in per) + f" | {f(sum(per), 0)} | {f(up, 0)} |")
    lines.append("")

    # Tab value.
    lines += ["## Tab value: what 4,800 souls in one tab adds, and what skipping it costs", "",
              "The first 4,800 souls in a tab reach that tab's big step (+46% weapon damage, +38% health, +38 spirit "
              "power). Same souls, three choices. Item stats not counted.", "",
              "| Checkpoint | Boons | Weapon: +gun DPS | Vitality: +health | Spirit: +kit damage (upgraded) |",
              "|---|---|---|---|---|"]
    for label, souls in CHECKPOINTS[1:4]:
        b = F.level_at(souls)["total_boons"]
        gun = F.gun_dps(name, b, 46) - F.gun_dps(name, b, 0)
        hp = F.health_with_vitality(name, b, 4800) - F.health_with_vitality(name, b, 0)
        sp0 = F.spirit_power_from_boons(name, b)
        kit0 = sum(ability_damage(owner_dmg, a, sp0, True) for a in kit)
        kit1 = sum(ability_damage(owner_dmg, a, sp0 + 38, True) for a in kit)
        lines.append(f"| {label} | {b} | +{f(gun, 0)} | +{f(hp, 0)} | +{f(kit1 - kit0, 0)} per full rotation |")
    lines += ["", f"Weapon investment at 12,800 souls adds +{f(ranks['weapon_value_raw'][name], 0)} gun DPS: ranks "
              f"{ranks['weapon_value'][name]} of 44 (1 = most). A low rank means skipping weapon items costs this hero "
              f"little gun damage.", ""]

    # Threat profile.
    hero_cc = [r for r in cc if r["owner"] == name]
    hard = sorted({r["cc_type"] for r in hero_cc if r["cc_type"] in HARD_CC})
    deny = sorted({r["cc_type"] for r in hero_cc if r["cc_type"] in DENIAL})
    slows = sorted({r["cc_type"] for r in hero_cc if "slow" in r["cc_type"]})
    dtypes = sorted({r["damage_type"] for r in owner_dmg if r["kind"] != "gun buff per bullet"})
    heals = [r for r in dfn if r["owner"] == name and r["effect"] in ("heal", "barrier")]
    anti = [r for r in dfn if r["owner"] == name and r["effect"] in ("anti-heal",)]
    shred = [r for r in dfn if r["owner"] == name and r["effect"] in ("resist reduction", "damage amp on target")]
    lines += ["## Threat profile: what this hero does to an opponent", "",
              f"- **Damage types:** gun (bullet){', ' + ', '.join(dtypes) if dtypes else ''}. "
              f"Gun DPS at 12,800 souls without items: {f(F.hero_stat(name, 'weapon_dps_level_1', 19))}; "
              f"upgraded kit at 50 spirit power: {f(totals[50][1], 0)} per rotation.",
              f"- **Hard control:** {', '.join(hard) or 'none found'}. **Action denial:** {', '.join(deny) or 'none'}. "
              f"**Slows:** {', '.join(slows) or 'none'}.",
              f"- **Healing and barriers in the kit:** {len(heals)} entries. **Anti-heal:** {len(anti)}. "
              f"**Resist reduction or amplification:** {len(shred)}.",
              f"- **Mobility:** {h['move_speed']} m/s, {h['stamina']} stamina.", ""]

    # Theory flags.
    flags = theory_flags(h, ranks, owner_dmg, hero_cc, totals)
    lines += ["## Openings for theories", "",
              "Automatic flags against the framework's theory types (`analysis/framework.md` §5). "
              "Starting points, not conclusions.", ""]
    lines += [f"- {x}" for x in flags] or ["- None flagged automatically."]
    lines += ["", "## Assumptions on this card", "",
              "- Gun DPS with weapon investment: all weapon damage % adds into one bonus on base + boon damage (Assumption; formulas.md test 1).",
              "- Vitality: the % applies to starting + boon health (Inferred; test 3).",
              "- Checkpoints use 1 / 2 / 5 ability point costs (Inferred, community-confirmed).",
              "- Damage types and control come from the keyword catalogues (`analysis/catalogues/README.md`).", ""]
    return "\n".join(lines)


def theory_flags(h, ranks, owner_dmg, hero_cc, totals):
    name = h["name"]
    out = []
    if ranks["shots"][name] <= 10:
        out.append(f"**Trigger carrier:** {f(F.shots_per_second(name), 1)} shots per second (rank {ranks['shots'][name]}). "
                   "On-hit and build-up items trigger often.")
    if h["spirit_scaling"]:
        out.append(f"**Crossover hook (spirit):** hero stats scale with spirit power: {h['spirit_scaling']}.")
    weapon_abilities = sorted({r["name"] for r in owner_dmg if r["damage_type"] == "weapon" and r["kind"] != "gun buff per bullet"})
    if weapon_abilities:
        out.append(f"**Crossover hook (weapon):** {', '.join(weapon_abilities)} deal weapon damage, so weapon investment "
                   "powers abilities, and bullet resist counters them.")
    melee = sorted({r["name"] for r in owner_dmg if r["damage_type"] == "melee"})
    if melee:
        out.append(f"**Melee hook:** {', '.join(melee)} scale with melee damage.")
    health_pct = sorted({r["name"] for r in owner_dmg if r["kind"] == "target health %"})
    if health_pct:
        out.append(f"**Self-sufficient damage:** damage based on the target's health ({', '.join(health_pct)}).")
    boon_scaling = [r for r in owner_dmg if "boon" in (r["other_scaling"] or "")]
    if ranks["weapon_value"][name] >= 34:
        out.append(f"**Cheap to skip weapon items:** weapon investment adds little gun damage (rank "
                   f"{ranks['weapon_value'][name]} of 44), so tank or spirit builds give up less.")
    if ranks["kit_gain"][name] <= 10:
        out.append(f"**Spirit scaling:** upgraded kit grows {f(totals[150][1] / max(totals[0][1], 1), 1)}× from 0 to "
                   f"150 spirit power (rank {ranks['kit_gain'][name]}).")
    if h["hero_type"] == "Healer" and ranks["kit_burst"][name] <= 22:
        out.append(f"**Surprise burst:** a Healer whose upgraded kit at 150 spirit power ranks {ranks['kit_burst'][name]} "
                   "of 44 for damage.")
    hard = {r["name"] for r in hero_cc if r["cc_type"] in HARD_CC}
    if len(hard) >= 2:
        out.append(f"**Control chain:** {len(hard)} abilities with hard control ({', '.join(sorted(hard))}). "
                   "Chaining them is shortened by diminishing returns (up to 21% within 7 s).")
    charges = [a for a in ranks["abilities"] if a["hero"] == name and not a["form"] and n(a["charges"]) and n(a["charges"]) > 1]
    if charges:
        out.append(f"**Charges:** {', '.join(a['name'] for a in charges)} store casts, so +charge items multiply them.")
    if ranks["health_per_boon"][name] <= 8:
        out.append(f"**Natural tank:** health per boon ranks {ranks['health_per_boon'][name]} of 44; resist multiplies a large pool.")
    if ranks["dps_growth"][name] <= 8:
        out.append(f"**Late gun:** gun growth ranks {ranks['dps_growth'][name]} of 44.")
    return out


# ---------------------------------------------------------------- all heroes


def rank(values, reverse=True):
    order = sorted(values, key=lambda k: values[k], reverse=reverse)
    return {k: i + 1 for i, k in enumerate(order)}


def build():
    heroes = F.table("heroes")
    ab = F.table("abilities")
    dmg, cc, dfn = rows("damage_sources"), rows("crowd_control"), rows("defence_sustain")
    names = [h["name"] for h in heroes]
    kit_totals = {}
    for h in heroes:
        kit = [a for a in ab if a["hero"] == h["name"] and not a["form"]]
        od = [r for r in dmg if r["owner"] == h["name"]]
        kit_totals[h["name"]] = {sp: sum(ability_damage(od, a, sp, True) for a in kit) for sp in REFERENCE_SP}
    weapon_value = {nm: F.gun_dps(nm, 19, 46) - F.gun_dps(nm, 19, 0) for nm in names}
    ranks = {
        "health_per_boon": rank({h["name"]: float(h["health_per_boon"]) for h in heroes}),
        "dps_growth": rank({h["name"]: float(h["dps_per_boon"]) / float(h["weapon_dps_level_1"]) for h in heroes}),
        "shots": rank({nm: F.shots_per_second(nm) for nm in names}),
        "weapon_value": rank(weapon_value), "weapon_value_raw": weapon_value,
        "kit_burst": rank({nm: kit_totals[nm][150] for nm in names}),
        "kit_gain": rank({nm: kit_totals[nm][150] / max(kit_totals[nm][0], 1) for nm in names}),
        "abilities": ab,
    }
    OUT.mkdir(exist_ok=True)
    summary = []
    for h in heroes:
        (OUT / f"{slug(h['name'])}.md").write_text(card(h, ab, dmg, cc, dfn, ranks), encoding="utf-8")
        hero_cc = [r for r in cc if r["owner"] == h["name"]]
        od = [r for r in dmg if r["owner"] == h["name"]]
        summary.append({
            "hero": h["name"], "type": h["hero_type"],
            "health_30k": F.hero_stat(h["name"], "base_health", 29),
            "gun_dps_30k": F.hero_stat(h["name"], "weapon_dps_level_1", 29),
            "shots_per_s": F.shots_per_second(h["name"]),
            "weapon_tab_gun_gain_12k8": weapon_value[h["name"]],
            "kit_upgraded_sp0": kit_totals[h["name"]][0], "kit_upgraded_sp150": kit_totals[h["name"]][150],
            "hard_cc": len({r["name"] for r in hero_cc if r["cc_type"] in HARD_CC}),
            "denial": ", ".join(sorted({r["cc_type"] for r in hero_cc if r["cc_type"] in DENIAL})),
            "damage_types": ", ".join(sorted({r["damage_type"] for r in od if r["kind"] != "gun buff per bullet"})),
            "flags": "; ".join(re.findall(r"\*\*(.+?):\*\*", "\n".join(
                theory_flags(h, ranks, od, hero_cc, {sp: (0, kit_totals[h["name"]][sp]) for sp in REFERENCE_SP})))),
        })
    with open(OUT / "hero_summary.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(summary[0]))
        w.writeheader()
        for s in summary:
            w.writerow({k: (round(v, 2) if isinstance(v, float) else v) for k, v in s.items()})
    index(summary)
    return len(summary)


def index(summary):
    lines = ["# Hero cards", "",
             "One card per hero, generated by `python analysis/hero_cards.py` (run `python analysis/catalogue.py` "
             "first). Each card has growth at the checkpoints, body, gun, every ability with its damage, control and "
             "upgrades, kit damage by spirit power, tab value, a threat profile and automatic theory flags.", "",
             "The kit figures are a rough comparison: one cast of each ability, upgraded, largest damage part. They "
             "flatter auras and channels (per-second damage at its listed maximum, for the whole base duration) and "
             "leave out scaling from melee damage, weapon damage % and boons, so melee and weapon-ability kits "
             "(Drifter, Silver, Venator, Rat King) read low. `hero_summary.csv` has the same table.", "",
             "| Hero | Type | Health 30k | Gun DPS 30k | Shots/s | Weapon tab +DPS | Kit 0 SP | Kit 150 SP | Hard CC abilities | Denial | Damage types | Flags |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in sorted(summary, key=lambda s: s["hero"]):
        lines.append(f"| [{s['hero']}]({slug(s['hero'])}.md) | {s['type']} | {f(s['health_30k'], 0)} | {f(s['gun_dps_30k'], 0)} | "
                     f"{f(s['shots_per_s'], 1)} | +{f(s['weapon_tab_gun_gain_12k8'], 0)} | {f(s['kit_upgraded_sp0'], 0)} | "
                     f"{f(s['kit_upgraded_sp150'], 0)} | {s['hard_cc']} | {s['denial']} | {s['damage_types']} | {s['flags']} |")
    lines += ["", "Columns: health and gun DPS at 29 boons (about 30,000 souls) without items; weapon tab +DPS is what "
              "4,800 souls of weapon investment adds at 12,800 souls; kit totals are upgraded kits at 0 and 150 spirit "
              "power.", ""]
    (OUT / "README.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    print(build(), "cards")
